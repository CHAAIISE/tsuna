// Regenerates src/contracts/specs.ts from the release builds of the contracts
// (`stellar contract build` in contracts/). The SDK encodes and decodes every call
// with these specs, so rerun this after changing a contract interface.
import { readFileSync, writeFileSync } from "node:fs";
import { stdout } from "node:process";
import { URL, fileURLToPath } from "node:url";
import { contract } from "@stellar/stellar-sdk";

const contracts = {
  agentVault: "agent_vault",
  policyRegistry: "policy_registry",
  vaultFactory: "vault_factory",
  oracleRouter: "oracle_router",
  signalBudget: "signal_budget",
};
const release = new URL("../../../contracts/target/wasm32v1-none/release/", import.meta.url);
const lines = [
  "// Generated by scripts/generate-specs.mjs from the release WASM builds. Do not edit.",
  "",
];
for (const [name, crate] of Object.entries(contracts)) {
  const spec = contract.Spec.fromWasm(readFileSync(new URL(`${crate}.wasm`, release)));
  const entries = spec.entries.map(entry => `  "${entry.toXDR("base64")}",`);
  lines.push(`export const ${name}: string[] = [`, ...entries, "];", "");
}
const target = fileURLToPath(new URL("../src/contracts/specs.ts", import.meta.url));
writeFileSync(target, lines.join("\n"));
stdout.write(`Wrote ${target}\n`);
